"""Build a portable, checksum-verified L2 bundle reproduction pack.

The public repository does not commit ``bundles/`` (it is generated by Isaac
Sim and listed in ``.gitignore``).  This script selects the input tables needed
by the E12 replay, writes a portable ``.tar.gz`` (fixed mtimes, sorted members)
plus a manifest, and copies the manifest into ``docs/repro/`` so the artifact
can be referenced from a GitHub release or Zenodo record.

Usage::

    python scripts/pack_repro_bundles.py --root bundles/dev --out dist/repro
    python scripts/pack_repro_bundles.py --include-images   # for detection reruns

Images are excluded by default: the replay only reads parquet tables, and
excluding the rendered Isaac frames keeps the pack small and avoids
redistributing simulator assets.  Derived replay outputs are excluded too;
they are regenerated by the replay.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import shutil
import subprocess
import tarfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

DEFAULT_ROOT = ROOT / "bundles" / "dev"
DEFAULT_OUT = ROOT / "dist" / "repro"
DEFAULT_MANIFEST_DIR = ROOT / "docs" / "repro"

DERIVED_FILES = {
    "entity_trace.parquet",
    "pred_states.parquet",
    "pred_relations.parquet",
    "pss_trace.parquet",
}

INPUT_FILES = {
    "manifest.json",
    "obs_frames.parquet",
    "obs_detections.parquet",
    "gt.parquet",
    "robot_state.parquet",
    "actions.parquet",
    "events.parquet",
    "detect_meta.json",
}


def _sha256(path: Path, chunk: int = 1 << 20) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            block = handle.read(chunk)
            if not block:
                break
            digest.update(block)
    return digest.hexdigest()


def _git_commit() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except Exception:
        return "unknown"


def _rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def _bundles(root: Path) -> list[Path]:
    out = []
    for det in sorted(root.glob("**/obs_detections.parquet")):
        bundle = det.parent
        if (
            (bundle / "manifest.json").exists()
            and (bundle / "gt.parquet").exists()
            and (bundle / "obs_detections.parquet").exists()
        ):
            out.append(bundle)
    return out


def _has_embedding(detections: Path) -> bool:
    import pandas as pd

    try:
        frame = pd.read_parquet(detections, columns=["emb"])
    except Exception:
        return False
    if "emb" not in frame.columns or frame.empty:
        return False
    return bool(frame["emb"].map(lambda value: value is not None and len(value) > 0).any())


def _files_for(
    bundle: Path,
    *,
    include_images: bool,
    include_derived: bool,
) -> list[Path]:
    files = []
    for path in sorted(bundle.rglob("*")):
        if not path.is_file():
            continue
        if path.name.startswith(".") or "__pycache__" in path.parts:
            continue
        if path.name in DERIVED_FILES and not include_derived:
            continue
        if "images" in path.relative_to(bundle).parts and not include_images:
            continue
        if path.name not in INPUT_FILES and not include_derived:
            # Unknown extra files are kept only when they are not derived
            # outputs; this preserves detector metadata without guessing.
            if path.suffix not in {".json", ".parquet", ".txt", ".md"}:
                continue
        files.append(path)
    return files


def _pack_readme(
    *,
    name: str,
    version: str,
    n_bundles: int,
    embedding_bundles: list[str],
    include_images: bool,
    git_commit: str,
) -> str:
    lines = [
        f"# {name} v{version}",
        "",
        "Input tables for the PSS L2 bundle replay (`E12`).  The runtime reads",
        "`obs_detections.parquet`; `gt.parquet` is used only for scoring, never",
        "for association.",
        "",
        "## Contents",
        "",
        f"- **{n_bundles} bundles** under `pss-bundles-v{version}/`.",
        f"- **{len(embedding_bundles)} bundles with detector embeddings** "
        "(GroundingDINO + DINOv2).",
        "- Per-bundle `manifest.json` records the spec hash, detector tier, and",
        "  the PSS commit that generated the bundle.",
        "- `PACK_MANIFEST.json` lists every file with its size and SHA256.",
        "- `LICENSE`, `NOTICE`, and `CITATION.cff` are included.",
        "- Images are "
        + ("included." if include_images else "excluded; the replay does not need them."),
        "- Derived replay outputs (`entity_trace`, `pred_states`, `pred_relations`,",
        "  `pss_trace`) are excluded; the replay regenerates them.",
        "",
        "## Quick start",
        "",
        "```bash",
        "mkdir -p bundles/repro",
        "tar -xzf "
        f"{name}-v{version}.tar.gz -C bundles/repro",
        "python scripts/reproduce_l2.py --root bundles/repro --out reports/repro",
        "```",
        "",
        "Or fetch and verify with:",
        "",
        "```bash",
        "python scripts/fetch_repro_bundles.py \\",
        f"  --archive {name}-v{version}.tar.gz \\",
        f"  --sha256 <archive sha256> --out bundles/repro",
        "```",
        "",
        "## Expected results",
        "",
        "| variant | valid bundles | ID retention | switches |",
        "|---|---:|---:|---:|",
        "| full | 19 | 1.000 | 0.00 |",
        "| no_memory | 19 | 0.827 | 0.56 |",
        "| no_entity | 19 | 0.270 | 47.47 |",
        "| no_relations | 19 | 1.000 | 0.00 |",
        "",
        "The 4 embedding bundles (`s1_hard`, `s1_occlusion_real`, `s2_twins`,",
        "`s1_camera_real`) show retention 1.000 for all variants.  They are the",
        "perception-level subset, not a memory-ablation signal; the memory signal",
        "comes from the occlusion/oracle bundles.",
        "",
        "## Provenance",
        "",
        f"- Repository commit at packaging time: `{git_commit}`.",
        "- Per-bundle manifests carry the original Isaac Sim, detector, and PSS",
        "  commit metadata.",
        "- License: Apache-2.0, matching the repository.  Generated data is",
        "  provided for reproducibility of the reported results.",
        "",
    ]
    return "\n".join(lines)


def _write_tar(stage: Path, archive: Path) -> None:
    archive.parent.mkdir(parents=True, exist_ok=True)
    with archive.open("wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9) as gz:
            with tarfile.open(fileobj=gz, mode="w") as tar:
                for path in sorted(stage.rglob("*")):
                    if not path.is_file():
                        continue
                    arcname = path.relative_to(stage.parent).as_posix()
                    info = tar.gettarinfo(str(path), arcname=arcname)
                    info.uid = info.gid = 0
                    info.uname = info.gname = ""
                    info.mtime = 0
                    info.mode = 0o644
                    with path.open("rb") as handle:
                        tar.addfile(info, handle)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(DEFAULT_ROOT))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--manifest-dir", default=str(DEFAULT_MANIFEST_DIR))
    ap.add_argument("--name", default="pss-l2-bundles")
    ap.add_argument("--version", default="0.1.1")
    ap.add_argument("--include-images", action="store_true")
    ap.add_argument("--include-derived", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    out = Path(args.out).resolve()
    manifest_dir = Path(args.manifest_dir).resolve()
    bundles = _bundles(root)
    if not bundles:
        raise SystemExit(f"no bundles found under {root}")

    stage = out / f"pss-bundles-v{args.version}"
    if stage.exists():
        if not args.force:
            raise SystemExit(f"{stage} already exists; pass --force to rebuild")
        shutil.rmtree(stage)

    copied: list[Path] = []
    embedding_bundles: list[str] = []
    for bundle in bundles:
        rel = bundle.relative_to(root)
        if _has_embedding(bundle / "obs_detections.parquet"):
            embedding_bundles.append(rel.as_posix())
        for path in _files_for(
            bundle,
            include_images=args.include_images,
            include_derived=args.include_derived,
        ):
            target = stage / rel / path.relative_to(bundle)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
            copied.append(target)

    # Carry the repository's license and attribution into the redistributed
    # artifact, not just the README summary.
    for name in ("LICENSE", "NOTICE", "CITATION.cff"):
        source = ROOT / name
        if source.exists():
            shutil.copy2(source, stage / name)

    readme = _pack_readme(
        name=args.name,
        version=args.version,
        n_bundles=len(bundles),
        embedding_bundles=embedding_bundles,
        include_images=args.include_images,
        git_commit=_git_commit(),
    )
    (stage / "README.md").write_text(readme, encoding="utf-8")

    files = []
    for path in sorted(stage.rglob("*")):
        if not path.is_file() or path.name == "PACK_MANIFEST.json":
            continue
        files.append(
            {
                "path": path.relative_to(stage).as_posix(),
                "bytes": path.stat().st_size,
                "sha256": _sha256(path),
            }
        )

    pack_manifest = {
        "name": args.name,
        "version": args.version,
        "created_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source_root": _rel(root),
        "git_commit": _git_commit(),
        "n_bundles": len(bundles),
        "bundles": [bundle.relative_to(root).as_posix() for bundle in bundles],
        "embedding_bundles": embedding_bundles,
        "include_images": bool(args.include_images),
        "include_derived": bool(args.include_derived),
        "derived_excluded": sorted(DERIVED_FILES),
        "files": files,
    }
    (stage / "PACK_MANIFEST.json").write_text(
        json.dumps(pack_manifest, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    archive = out / f"{args.name}-v{args.version}.tar.gz"
    _write_tar(stage, archive)
    archive_sha = _sha256(archive)
    manifest = dict(pack_manifest)
    manifest["archive"] = {
        "path": archive.name,
        "bytes": archive.stat().st_size,
        "sha256": archive_sha,
    }
    manifest["pack_manifest_sha256"] = _sha256(stage / "PACK_MANIFEST.json")

    out.mkdir(parents=True, exist_ok=True)
    manifest_dir.mkdir(parents=True, exist_ok=True)
    manifest_name = f"PSS_BUNDLES_v{args.version}.json"
    for directory in (out, manifest_dir):
        (directory / manifest_name).write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        (directory / "SHA256SUMS").write_text(
            f"{archive_sha}  {archive.name}\n",
            encoding="utf-8",
        )

    print(f"bundles:        {len(bundles)}")
    print(f"embedding:      {len(embedding_bundles)}")
    print(f"files:          {len(files)}")
    print(f"archive:        {archive} ({archive.stat().st_size / 1e6:.1f} MB)")
    print(f"archive sha256: {archive_sha}")
    print(f"manifest:       {manifest_dir / manifest_name}")
    print(f"stage:          {stage}")


if __name__ == "__main__":
    main()
